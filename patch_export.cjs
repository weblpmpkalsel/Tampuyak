const fs = require('fs');
let code = fs.readFileSync('src/DocumentExportEngine.ts', 'utf-8');

code = code.replace(
  "import { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, BorderStyle, WidthType, Footer, AlignmentType, PageNumber } from 'docx';",
  "import { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, BorderStyle, WidthType, Footer, AlignmentType, PageNumber, PageOrientation } from 'docx';"
);

// We need to group children by chapter so they become sections
const replaceGenerateDocx = `  public async generateDocx(model: DocumentModel, metadata: ExportMetadata): Promise<string> {
    const chapters = [
      model.cover,
      model.approval,
      model.toc,
      model.chapter1,
      model.chapter2,
      model.chapter3,
      model.chapter4,
      model.chapter5,
      model.appendix
    ].filter(Boolean);

    const docSections: any[] = [];

    // Add metadata page as first section
    const metadataChildren: any[] = [];
    metadataChildren.push(
      new Paragraph({
        text: metadata.title,
        heading: HeadingLevel.TITLE,
        alignment: AlignmentType.CENTER,
        spacing: { before: 2400, after: 1200 },
      }),
      new Paragraph({
        text: \`Generated By: \${metadata.generatedBy} | Version \${metadata.version} | Score: \${metadata.qualityScore}%\`,
        alignment: AlignmentType.CENTER,
        spacing: { after: 400 },
      }),
      new Paragraph({
        text: "Digital Verification: " + (metadata.qrCode || "VERIFIED"),
        alignment: AlignmentType.CENTER,
        pageBreakBefore: false,
      })
    );

    docSections.push({
      properties: {},
      footers: {
        default: new Footer({
          children: [
            new Paragraph({
              alignment: AlignmentType.CENTER,
              children: [
                new TextRun({ children: [PageNumber.CURRENT] }),
                new TextRun(" / "),
                new TextRun({ children: [PageNumber.TOTAL_PAGES] }),
              ],
            })
          ],
        }),
      },
      children: metadataChildren,
    });

    chapters.forEach(chapter => {
      const chapterChildren: any[] = [];
      chapterChildren.push(
        new Paragraph({
          text: chapter.title,
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 400, after: 400 },
        })
      );

      if (chapter.subtitle) {
        chapterChildren.push(
          new Paragraph({
            text: chapter.subtitle,
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 200, after: 400 },
          })
        );
      }

      chapter.paragraphs?.forEach(p => {
        chapterChildren.push(
          new Paragraph({
            text: p,
            spacing: { after: 200 },
          })
        );
      });

      chapter.sections?.forEach((section: DocumentSection) => {
        if (section.title) {
          chapterChildren.push(
            new Paragraph({
              text: section.title,
              heading: HeadingLevel.HEADING_2,
              spacing: { before: 400, after: 200 },
            })
          );
        }
        section.paragraphs?.forEach(p => {
          chapterChildren.push(
            new Paragraph({
              text: p,
              spacing: { after: 200 },
            })
          );
        });
      });

      const sectionProps = chapter.orientation === 'landscape' ? {
        page: { size: { orientation: PageOrientation.LANDSCAPE } }
      } : {};

      docSections.push({
        properties: sectionProps,
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({ children: [PageNumber.CURRENT] }),
                  new TextRun(" / "),
                  new TextRun({ children: [PageNumber.TOTAL_PAGES] }),
                ],
              })
            ],
          }),
        },
        children: chapterChildren,
      });
    });

    const doc = new Document({
      sections: docSections,
    });

    const blob = await Packer.toBlob(doc);
    return URL.createObjectURL(blob);
  }`;

code = code.replace(/public async generateDocx[\s\S]*?const blob = await Packer\.toBlob\(doc\);\n    return URL\.createObjectURL\(blob\);\n  }/m, replaceGenerateDocx);

fs.writeFileSync('src/DocumentExportEngine.ts', code);
console.log("DocumentExportEngine patched for DOCX sections!");
