// Remove static import
import { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, BorderStyle, WidthType, Footer, AlignmentType, PageNumber, PageOrientation } from 'docx';
import { DocumentModel, DocumentChapter, DocumentSection } from './DocumentCompositionEngine/DocumentModel';
import html2pdf from 'html2pdf.js/dist/html2pdf.bundle.min.js';
import { EnterpriseLayoutRegistry } from './enterprise/document/layout/LayoutEngine';

export interface ExportMetadata {
  title: string;
  generatedBy: string;
  version: number;
  qrCode?: string;
  qualityScore: number;
}

export class DocumentExportEngine {
  
    public async generateDocx(model: DocumentModel, metadata: ExportMetadata): Promise<string> {
    const chapters = [
      model.cover,
      model.approval,
      model.toc,
      model.chapter1,
      model.chapter2,
      model.chapter3,
      model.chapter4,
      model.chapter5,
      model.appendix
    ].filter(Boolean);

    const docSections: any[] = [];

    // Add metadata page as first section
    const metadataChildren: any[] = [];
    metadataChildren.push(
      new Paragraph({
        text: metadata.title,
        heading: HeadingLevel.TITLE,
        alignment: AlignmentType.CENTER,
        spacing: { before: 2400, after: 1200 },
      }),
      new Paragraph({
        text: `Generated By: ${metadata.generatedBy} | Version ${metadata.version} | Score: ${metadata.qualityScore}%`,
        alignment: AlignmentType.CENTER,
        spacing: { after: 400 },
      }),
      new Paragraph({
        text: "Digital Verification: " + (metadata.qrCode || "VERIFIED"),
        alignment: AlignmentType.CENTER,
        pageBreakBefore: false,
      })
    );

    docSections.push({
      properties: {},
      footers: {
        default: new Footer({
          children: [
            new Paragraph({
              alignment: AlignmentType.CENTER,
              children: [
                new TextRun({ children: [PageNumber.CURRENT] }),
                new TextRun(" / "),
                new TextRun({ children: [PageNumber.TOTAL_PAGES] }),
              ],
            })
          ],
        }),
      },
      children: metadataChildren,
    });

    const fixedIds = ["cover", "approval", "toc", "bab1", "bab2", "bab3", "bab4", "bab5", "lampiran"];
    chapters.forEach((chapter, index) => {
      const fixedId = fixedIds[index];
      const chapterLayout = EnterpriseLayoutRegistry.getLayout(fixedId || chapter.id, metadata.title);
      const chapterChildren: any[] = [];
      chapterChildren.push(
        new Paragraph({
          text: chapter.title,
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 400, after: 400 },
        })
      );

      if (chapter.subtitle) {
        chapterChildren.push(
          new Paragraph({
            text: chapter.subtitle,
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 200, after: 400 },
          })
        );
      }

      chapter.paragraphs?.filter(p => p.trim() !== "").forEach(p => {
        chapterChildren.push(
          new Paragraph({
            text: p,
            spacing: { after: 200 },
          })
        );
      });

      chapter.sections?.forEach((section: DocumentSection) => {
        if (section.title) {
          chapterChildren.push(
            new Paragraph({
              text: section.title,
              heading: HeadingLevel.HEADING_2,
              spacing: { before: 400, after: 200 },
            })
          );
        }
        section.paragraphs?.filter(p => p.trim() !== "").forEach(p => {
          chapterChildren.push(
            new Paragraph({
              text: p,
              spacing: { after: 200 },
            })
          );
        });
        
        section.tables?.forEach(table => {
           if (table.type === 'signature_block') {
             chapterChildren.push(
                new Paragraph({
                  text: table.location,
                  alignment: AlignmentType.RIGHT,
                  spacing: { before: 800, after: 400 }
                })
             );
             
             const sigCells = table.signatures.map((sig: any) => {
                return new TableCell({
                   borders: {
                      top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                      bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                      right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                   },
                   children: [
                      new Paragraph({
                         text: sig.label.replace('\n', ' '),
                         alignment: AlignmentType.CENTER,
                         spacing: { after: 2400 } // approx 4-5cm space
                      }),
                      new Paragraph({
                         text: sig.name,
                         alignment: AlignmentType.CENTER,
                         style: "Strong" // Bold equivalent if "Strong" style is missing might fall back, let's use TextRun
                      }),
                      new Paragraph({
                         text: `NIP. ${sig.nip}`,
                         alignment: AlignmentType.CENTER,
                      })
                   ]
                });
             });
             
             
             const sigTable = new Table({
                width: { size: 100, type: WidthType.PERCENTAGE },
                borders: {
                    top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                    bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                    left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                    right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                    insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                    insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
                },
                rows: [
                   new TableRow({
                      children: sigCells
                   })
                ]
             });
             
             chapterChildren.push(sigTable);
           }
        });
      });

      const sectionProps = chapterLayout.orientation === 'landscape' ? {
        page: { size: { orientation: PageOrientation.LANDSCAPE } }
      } : {};

      docSections.push({
        properties: sectionProps,
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({ children: [PageNumber.CURRENT] }),
                  new TextRun(" / "),
                  new TextRun({ children: [PageNumber.TOTAL_PAGES] }),
                ],
              })
            ],
          }),
        },
        children: chapterChildren,
      });
    });

    const doc = new Document({
      sections: docSections,
    });

    const blob = await Packer.toBlob(doc);
    return URL.createObjectURL(blob);
  }

  public async generatePDF(htmlContent: HTMLElement | string, metadata: ExportMetadata): Promise<string> {
    let isLandscape = false;
    if (typeof htmlContent === 'string') {
      isLandscape = htmlContent.includes('landscape-section');
    } else {
      isLandscape = htmlContent.classList.contains('landscape-section') || htmlContent.querySelector('.landscape-section') !== null;
    }

    const opt = {
      margin:       0,
      filename:     `${metadata.title}.pdf`,
      image:        { type: 'jpeg', quality: 0.98 },
      html2canvas:  { 
        scale: 2, 
        useCORS: true,
        onclone: (clonedDoc: HTMLDocument) => {
          // Force print styles for PDF export without modifying document geometry
          const printStyle = clonedDoc.createElement('style');
          printStyle.innerHTML = `
            *, *::before, *::after { box-sizing: border-box !important; animation: none !important; transition: none !important; }
            tr, td, th { page-break-inside: avoid; break-inside: avoid; word-break: break-word !important; }
            thead { display: table-header-group; }
            tfoot { display: table-footer-group; }
            h2, h3, h4, h5, h6 { page-break-after: avoid; break-after: avoid; page-break-inside: avoid; break-inside: avoid; }
            p { orphans: 3; widows: 3; hyphens: auto !important; }
          `;
          clonedDoc.head.appendChild(printStyle);
        }
      },
      pagebreak:    { mode: ['css', 'legacy'] }, 
      jsPDF:        { unit: 'in', format: 'a4', orientation: isLandscape ? 'landscape' : 'portrait' }
    };

    const originalGetComputedStyle = window.getComputedStyle;
    const proxyGetComputedStyle = function(el: Element, pseudoElt?: string | null) {
      const style = originalGetComputedStyle(el, pseudoElt);
      return new Proxy(style, {
        get(target: any, prop: string | symbol) {
          if (prop === 'getPropertyValue') {
            return function(propName: string) {
              let val = target.getPropertyValue(propName);
              if (val && typeof val === 'string' && val.includes('oklch')) {
                // Approximate fallback for known tailwind shades
                if (val.includes('0.968 0.007 247.896')) return 'rgb(241, 245, 249)'; // slate-100
                if (val.includes('0.985 0 0')) return 'rgb(248, 250, 252)'; // slate-50
                if (val.includes('0.278 0.033 256.848')) return 'rgb(15, 23, 42)'; // slate-900
                if (val.includes('0.379 0.043 257.287')) return 'rgb(30, 41, 59)'; // slate-800
                if (val.includes('0.463 0.046 258.337')) return 'rgb(51, 65, 85)'; // slate-700
                
                if (propName.includes('background') && val.includes(' 0 ')) return 'rgb(255, 255, 255)'; // probably white
                
                if (propName.includes('background')) return 'rgb(241, 245, 249)'; // fallback light
                return 'rgb(15, 23, 42)'; // fallback dark text
              }
              return val;
            };
          }
          let val = target[prop];
          if (typeof val === 'string' && val.includes('oklch')) {
            if (prop.toString().includes('background')) return 'rgb(255, 255, 255)';
            return 'rgb(0, 0, 0)';
          }
          if (typeof val === 'function') {
            return val.bind(target);
          }
          return val;
        }
      });
    };

    window.getComputedStyle = proxyGetComputedStyle as any;

    try {
      (/* console.log removed */ (..._args: any[]) => {})("DOM elements before export:", typeof htmlContent === 'string' ? "string" : htmlContent.querySelectorAll('*').length);
      const pdfBlob = await html2pdf().from(htmlContent).set(opt as any).output('blob');
      return URL.createObjectURL(pdfBlob);
    } finally {
      window.getComputedStyle = originalGetComputedStyle;
    }
  }
}
